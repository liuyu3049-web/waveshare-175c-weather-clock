// Reference artwork coordinates before the outer case was cropped.
static constexpr float blackHandScale=233.f/204, whiteHandScale=233.f/216, greenHandScale=233.f/203;
static float handCoord(float coordinate, float scale) { return 232.5f+(coordinate-232.5f)*scale; }

static void referenceBlade(const RefBlade& blade, float cx, float cy, float a, float scale, bool shadow=false) {
  cx=handCoord(cx,scale); cy=handCoord(cy,scale);
  const float inverse=1.f/scale;
  const float dx=sinf(a), dy=-cosf(a);
  const bool horizontal=fabsf(dx)>fabsf(dy);
  const float major=horizontal?dx:dy, minor=horizontal?dy:dx;
  const float origin=horizontal?cx:cy, acrossOrigin=horizontal?cy:cx;
  const float blur=shadow?1.4f:0.5f;
  const float extent=(blade.radius+blur)*scale;
  const int start=int(floorf(origin+scale*fminf(blade.start*major,blade.end*major)-extent));
  const int stop=int(ceilf(origin+scale*fmaxf(blade.start*major,blade.end*major)+extent));
  const float rowScale=(blade.rows-1)/(blade.end-blade.start), slope=minor/major;
  const float ribbon=extent/fabsf(major);
  for (int i=start; i<=stop; ++i) {
    const float line=acrossOrigin+(i-origin)*slope;
    const int first=int(floorf(line-ribbon)), last=int(ceilf(line+ribbon));
    for (int j=first; j<=last; ++j) {
      const int x=horizontal?i:j, y=horizontal?j:i;
      const float u=((x-cx)*dx+(y-cy)*dy)*inverse, v=((y-cy)*dx-(x-cx)*dy)*inverse;
      if (u<blade.start-blur || u>blade.end+blur) continue;
      const float row=fminf(blade.rows-1.f,fmaxf(0,(u-blade.start)*rowScale));
      const int k=(int)row;
      const float t=row-k;
      const uint8_t* p=blade.levels+13*k;
      const uint8_t* q=k+1<blade.rows?p+13:p;
      const float left=(p[0]+t*(int(q[0])-p[0])-64)*.25f;
      const float right=(p[1]+t*(int(q[1])-p[1])-64)*.25f;
      const float edge=fminf(fminf(v-left,right-v),fminf(u-blade.start,blade.end-u));
      if (edge<=-blur) continue;
      uint16_t& dst=fb[y*size+x];
      if (shadow) {
        const float opacity=fminf(1,(edge+blur)/(2*blur));
        dst=mix(dst,0,(unsigned)(5*opacity+.5f));
      } else {
        const float sample=fminf(10,fmaxf(0,(v-left)*10/fmaxf(.125f,right-left)));
        const int n=(int)sample;
        const float f=sample-n;
        const int next=n<10?n+1:n;
        const float lo=p[2+n]+f*(int(p[2+next])-p[2+n]);
        const float hi=q[2+n]+f*(int(q[2+next])-q[2+n]);
        const int level=int(lo+t*(hi-lo)+.5f);
        const auto tone=rgb(level,level,level);
        dst=edge>=.5f?tone:mix(dst,tone,(unsigned)((edge+.5f)*15+.5f));
      }
    }
  }
}

static void referenceCap(const RefCap& cap, float cx, float cy, float scale, float rotation=0) {
  cx=handCoord(cx,scale); cy=handCoord(cy,scale);
  const int r=cap.radius, side=2*r+1;
  const float bound=(cap.silhouette+.5f)*scale, inverse=1.f/scale;
  const float c=cosf(rotation), s=sinf(rotation);
  for (int y=int(floorf(cy-bound)); y<=int(ceilf(cy+bound)); ++y) {
    for (int x=int(floorf(cx-bound)); x<=int(ceilf(cx+bound)); ++x) {
      const float dx=(x-cx)*inverse, dy=(y-cy)*inverse, d2=dx*dx+dy*dy;
      if (d2>(cap.silhouette+.5f)*(cap.silhouette+.5f)) continue;
      const float u=fminf(side-1.f,fmaxf(0,dx*c+dy*s+r)), v=fminf(side-1.f,fmaxf(0,dy*c-dx*s+r));
      const int col=(int)u, row=(int)v;
      const float fx=u-col, fy=v-row;
      const uint8_t* top=cap.levels+row*side;
      const uint8_t* bottom=row+1<side?top+side:top;
      const int next=col+1<side?col+1:col;
      const float lo=top[col]+fx*(int(top[next])-top[col]);
      const float hi=bottom[col]+fx*(int(bottom[next])-bottom[col]);
      const int level=int(lo+fy*(hi-lo)+.5f);
      const uint16_t ink=rgb(level,level,level);
      uint16_t& dst=fb[y*size+x];
      if (d2<(cap.silhouette-.5f)*(cap.silhouette-.5f)) dst=ink;
      else dst=mix(dst,ink,(unsigned)((cap.silhouette+.5f-sqrtf(d2))*15+.5f));
    }
  }
}

static void referenceHourMinute(uint8_t face, const tm& t) {
  const bool black=face==ClockExplorer, white=face==ClockMoonwatch;
  const float cx=black?235:white?233:173, cy=black||white?228:185;
  const RefBlade& hour=black?blackHour:white?whiteHour:greenHour;
  const RefBlade& minute=black?blackMinute:white?whiteMinute:greenMinute;
  const float scale=black?blackHandScale:white?whiteHandScale:greenHandScale;
  constexpr float step=.10471975512f;
  if (white) {
    referenceBlade(whiteSeconds,326,230,t.tm_mday*(60.f/31)*step,scale);
    referenceCap(whiteSmallPivot,326,230,scale);
    referenceBlade(whiteSeconds,232,319,(t.tm_mon+1)*5*step,scale);
    referenceCap(whiteSmallPivot,232,319,scale);
  }
  const float h=(5*(t.tm_hour%12)+t.tm_min/12.f)*step, m=t.tm_min*step;
  referenceBlade(hour,cx+1.4f,cy+2.4f,h,scale,true);
  referenceBlade(minute,cx+1.4f,cy+2.4f,m,scale,true);
  referenceBlade(hour,cx,cy,h,scale);
  referenceBlade(minute,cx,cy,m,scale);
  if (black) {
    const float distance=minute.end*.64f;
    // Align the original three-spoke disc with the long hand; the source points at 10.
    referenceCap(blackMinuteDisc,cx+distance*sinf(m),cy-distance*cosf(m),scale,m+1.014f);
  } else referenceCap(white?whitePivot:greenPivot,cx,cy,scale);
}

static void referenceSecondsBlack(float s) {
  const float a=s*.10471975512f, dx=sinf(a), dy=-cosf(a);
  referenceBlade(blackSeconds,235,228,a,blackHandScale);
  referenceCap(blackPearl,235+103.4f*dx,228+103.4f*dy,blackHandScale);
  referenceCap(blackPivot,235,228,blackHandScale);
}

static void referenceSecondsWhite(float s) {
  referenceBlade(whiteRunning,141,230,s*.10471975512f,whiteHandScale);
  referenceCap(whiteRunningPivot,141,230,whiteHandScale);
}

static void referenceSecondsGreen(float s) {
  const float a=s*.10471975512f;
  referenceBlade(greenSeconds,158.2f,325.4f,a,greenHandScale,true);
  referenceBlade(greenSeconds,157,324,a,greenHandScale);
  referenceCap(greenSmallPivot,157,324,greenHandScale);
}

