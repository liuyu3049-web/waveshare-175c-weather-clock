inline void renderClockSky(uint16_t* fb, bool night, int wmo) {
    using namespace clock_sky;
    const bool cloudy = wmo >= 3;
    const Palette& p = night ? evening : (cloudy ? rain : dawn);
    constexpr int keyY[] = {0, 100, 174, 220, 249, 286};
    constexpr int ridgeY[] = {247, 285, 312, 347};
    constexpr int valleyY[] = {298, 339, 363, 458};
    int segment = 0;
    uint32_t noise = 0x75ac49d1;
    for (int y = 0; y < 466; ++y) {
        if (segment < 4 && y >= keyY[segment+1]) ++segment;
        Ink sky = mix(p.sky[segment], p.sky[segment+1], ramp(y, keyY[segment], keyY[segment+1]));
        Ink hills[4];
        for (int layer = 0; layer < 4; ++layer)
            hills[layer] = mix(p.ridge[layer], p.valley[layer], ramp(y, ridgeY[layer], valleyY[layer]));
        const int hazeY = 100 - (y > 252 ? (y-252)*2 : (252-y)*2);
        for (int x = 0; x < 466; ++x) {
            // GCC folds the constant divisions; every ridge is shared by the three skies.
            const int i = x >> 1, odd = x & 1;
            Ink col = sky;
            if (y >= 235) {
                for (int layer = 3; layer >= 0; --layer) {
                    const uint8_t* profile = ridges[layer];
                    const int crest = 224 + ((profile[i] + profile[i+odd]) >> 1);
                    if (y < crest) continue;
                    col = hills[layer];
                    if (layer == 0 && crest < 269) {
                        const int lean = (int)profile[i+(i < 231 ? 2 : 0)] - profile[i];
                        const int depth = ((269-crest)*(lean > 0 ? 5 : 2)) >> 3;
                        if (y-crest < depth) col = mix(col, p.snow, lean > 0 ? 212 : 109);
                    }
                    break;
                }
            }
            // Off-centre horizon light dissolves into the distant peaks.
            if (hazeY > 0 && y < 224 + ridges[1][i]) {
                const int distance = x > 114 ? x-114 : 114-x;
                const int glow = distance < 170 ? hazeY * (170-distance) >> 10 : 0;
                col.r += glow;
                col.g += glow >> 1;
                if (cloudy || night) col.b += glow >> 1;
            }
            noise ^= noise << 13;
            noise ^= noise >> 17;
            noise ^= noise << 5;
            fb[y * 466 + x] = packed(col, noise >> 24);
        }
    }
    if (night && !cloudy) {
        constexpr uint16_t stars[][2] = {{109,69},{124,93},{164,49},{171,64},{167,78},{210,32},{271,60},
                                          {299,85},{324,51},{354,85},{371,116},{82,131},{65,152},
                                          {127,157},{384,169},{397,156},{352,196},{91,188}};
        for (unsigned i = 0; i < sizeof(stars)/sizeof(stars[0]); ++i) {
            int at = stars[i][1]*466 + stars[i][0];
            fb[at] = packed(i%4 == 0 ? Ink{166,179,195} : Ink{106,120,145}, 0);
        }
    }
}

inline void drawClockSky(uint16_t* fb, bool night, int wmo) {
#ifdef ESP32
    constexpr size_t bytes = 466 * 466 * sizeof(uint16_t);
    static uint16_t* sky = static_cast<uint16_t*>(ps_malloc(bytes));
    static int previous = -1;
    if (sky) {
        const int palette = 2 * int(night) + int(wmo >= 3);
        if (previous != palette) {
            renderClockSky(sky, night, wmo);
            previous = palette;
        }
        memcpy(fb, sky, bytes);
        return;
    }
#endif
    renderClockSky(fb, night, wmo);
}

