inline int ramp(int value, int start, int end) {
    if (value <= start) return 0;
    if (value >= end) return 256;
    return (value - start) * 256 / (end - start);
}

inline Ink mix(Ink a, Ink b, int amount) {
    return {a.r + ((b.r-a.r)*amount >> 8), a.g + ((b.g-a.g)*amount >> 8),
            a.b + ((b.b-a.b)*amount >> 8)};
}

inline uint16_t packed(Ink c, int dither) {
    return (uint16_t)(((c.r + (dither & 7)) >> 3) << 11 |
                      ((c.g + ((dither >> 3) & 3)) >> 2) << 5 |
                      ((c.b + ((dither >> 5) & 7)) >> 3));
}
